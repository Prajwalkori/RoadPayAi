def get_settings(db: Session) -> Settings:
    settings = db.query(Settings).filter(Settings.id == 1).first()
    if not settings:
        settings = Settings(id=1)
        db.add(settings)
        db.commit()
        db.refresh(settings)
    return settings

def get_gemini_client(db: Session) -> str | None:
    settings = get_settings(db)
    return settings.gemini_api_key or os.getenv("GEMINI_API_KEY") or os.getenv("GROQ_API_KEY")

def clean_markdown_text(text: str) -> str:
    """
    Cleans markdown code blocks (e.g. ```json ... ``` or ```html ... ```)
    from the raw text generated by the AI model.
    """
    text = text.strip()
    match = re.search(r"```(?:json|html)?\s*(.*?)\s*```", text, re.DOTALL)
    if match:
        return match.group(1).strip()
    return text

