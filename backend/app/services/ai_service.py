async def generate_email_content(violation_details: Dict[str, Any], db: Session) -> str:
    """
    Builds a complete HTML email using a Python template (always reliable),
    and enriches the AI explanation paragraph via Gemini.
    This guarantees due date, payment link, quiz link, and fine amount are
    ALWAYS present regardless of Gemini's output.
    """
    client = get_gemini_client(db)

    owner_name    = violation_details.get("owner_name", "Citizen")
    vehicle_number = violation_details.get("vehicle_number", "N/A")
    violation_type = violation_details.get("violation_type", "Traffic Violation").replace("_", " ")
    amount        = violation_details.get("amount", "500")
    due_date      = violation_details.get("due_date", "7 days from today")
    payment_link  = violation_details.get("payment_link") or violation_details.get("payment_url", "#")
    learning_link = violation_details.get("learning_link", "#")
    explanation   = violation_details.get("explanation", "")

    # Step 1: Try Gemini ONLY for the explanation paragraph (2-3 sentences max)
    ai_explanation = explanation  # start with existing explanation from violation detection
    if client and not ai_explanation:
        try:
            prompt = f"""Write a 2-sentence empathetic safety explanation for a {violation_type} traffic violation.
Focus on the specific danger it causes and the safety benefit of complying.
Return plain text only — no HTML, no markdown, no formatting."""
            ai_explanation = generate_content_with_fallback(client, prompt).strip()
            print(f"[Email] AI explanation generated: {ai_explanation[:80]}...")
        except Exception as e:
            print(f"[Email] Gemini explanation failed: {e}. Using default.")

    if not ai_explanation:
        ai_explanation = (
            f"A {violation_type} puts you and others at serious risk on the road. "
            "Please review the safety guidelines and complete the learning module to stay safe."
        )

    # Step 2: Always use the Python template — guaranteed to have all fields
    return simulate_email_generation(
        owner_name, vehicle_number, violation_type, amount,
        due_date, payment_link, learning_link, ai_explanation
    )


