def generate_content_with_fallback(api_key: str, contents) -> str:
    """
    Generates content using Google Gemini with vision support.
    Tries models in order with a short backoff between attempts.
    """
    import time
    try:
        from google import genai
        from google.genai import types
    except ImportError as e:
        raise RuntimeError(f"[Gemini] google-genai package not installed: {e}. Run: pip install google-genai") from e

    client = genai.Client(api_key=api_key)

    # ── Build the parts list for the Gemini request ────────────────────────
    parts = []
    if isinstance(contents, list):
        for item in contents:
            if isinstance(item, str):
                parts.append(item)
            else:
                # PIL Image → convert to inline data
                try:
                    buffered = io.BytesIO()
                    item.save(buffered, format="JPEG")
                    img_bytes = buffered.getvalue()
                    parts.append(
                        types.Part.from_bytes(data=img_bytes, mime_type="image/jpeg")
                    )
                except Exception as e:
                    print(f"[Gemini] Error encoding image: {e}")
    else:
        parts.append(str(contents))

    models = [
        "gemini-3.5-flash",               # ✅ Primary: 2/20 RPD used, 18 remaining
        "gemini-2.0-flash",               # Fallback: may have separate quota
        "gemini-2.0-flash-lite",          # Lighter fallback
        "gemini-2.5-flash",               # Last resort (currently over daily quota)
    ]

    last_error = None
    for i, model in enumerate(models):
        try:
            print(f"[Gemini] Trying model: {model}")
            response = client.models.generate_content(
                model=model,
                contents=parts,
                config=types.GenerateContentConfig(
                    temperature=0.1,
                    max_output_tokens=2048,
                )
            )
            print(f"[Gemini] ✓ Success with model: {model}")
            return response.text.strip()
        except Exception as e:
            err_msg = str(e)
            is_quota = any(x in err_msg.lower() for x in ["429", "quota", "resource_exhausted", "rate limit"])
            if is_quota:
                print(f"[Gemini] ⚠ Quota/rate limit on {model}. Trying next model in 1s...")
                time.sleep(1)
            else:
                print(f"[Gemini] ✗ Model {model} failed: {err_msg[:200]}")
            last_error = e
            continue

    raise RuntimeError(
        f"[Gemini] All models quota-exhausted or unavailable. Last error: {last_error}. "
        f"Free tier: 15 req/min. Upgrade at https://aistudio.google.com or wait 1 minute."
    ) from last_error





async def analyze_violation_image(image_bytes: bytes, db: Session) -> Dict[str, Any]:
    """
    Gemini Vision pipeline — single multimodal call.
    Gemini reads both the violation AND the number plate directly from the image.
    No external OCR library needed; Gemini's vision capability handles plate detection.
    """
    client = get_gemini_client(db)
    if not client:
        return simulate_image_analysis()

    try:
        image = Image.open(io.BytesIO(image_bytes))

        prompt = """
        You are RoadPay AI, an expert traffic enforcement vision model for India.
        Carefully analyze this traffic camera image.

        TASK 1 — NUMBER PLATE EXTRACTION (priority: high accuracy)
        Zoom into every vehicle visible in the image and read its registration plate.
        Indian plates follow this format: 2-letter state code + 2-digit district + 
        1-3 letters + 4 digits (e.g. MH12AB1234, DL3CAF8144, UP32MD5678).
        • Read each character individually. Common confusions to watch for:
          - 0 vs O,  1 vs I vs L,  8 vs B,  5 vs S,  6 vs G,  2 vs Z
        • Return the plate exactly as printed (no spaces, all uppercase).
        • If multiple vehicles are visible, return the plate of the vehicle committing the violation.

        TASK 2 — VIOLATION DETECTION
        Identify if any of the following violations are present:
          - HELMET_VIOLATION  : rider on motorcycle not wearing a helmet
          - TRIPLE_RIDING     : more than 2 people on a single motorcycle
          - WRONG_DIRECTION   : vehicle driving against traffic flow / wrong way
        If no violation is clearly visible, set detected to false.

        TASK 3 — SAFETY EXPLANATION
        Write a concise (max 2 sentences), empathetic explanation of why this violation 
        is dangerous and the benefit of following the rule.

        Respond ONLY with a valid JSON object (no markdown, no code blocks). Schema:
        {
          "detected": true,
          "violation_type": "HELMET_VIOLATION" | "TRIPLE_RIDING" | "WRONG_DIRECTION",
          "vehicle_number": "STRING (plate exactly as read, no spaces, uppercase)",
          "confidence_score": 0.95,
          "explanation": "STRING"
        }
        If no violation is detected, set detected to false and leave other fields as empty strings.
        """

        response_text = generate_content_with_fallback(client, [prompt, image])
        response_text = clean_markdown_text(response_text)

        if not response_text or not response_text.strip():
            print("[Gemini] Empty response received. Falling back to simulation.")
            return simulate_image_analysis()

        try:
            data = json.loads(response_text)
        except json.JSONDecodeError as je:
            print(f"[Gemini] Invalid JSON response: {je}\nRaw response: {response_text[:300]}")
            return simulate_image_analysis()

        return data

    except Exception as e:
        print(f"[Gemini] Analysis error: {e}. Falling back to simulation.")
        return simulate_image_analysis()


